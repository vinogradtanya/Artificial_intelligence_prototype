"""Простая модерация промпта по списку запрещённых слов.

В учебном прототипе модерация выполняется НЕ моделью, а проверкой
по массиву строк (аналог str.includes). См. docs/ТЗ.md.
"""
import re

# Список запрещённых слов/подстрок. В реальной системе хранился бы в БД
# и редактировался администратором; здесь — статический массив строк.
FORBIDDEN_WORDS = [
    "наркотик",
    "наркотики",
    "оружие",
    "бомба",
    "взрывчатка",
    "терроризм",
    "террорист",
    "убийство",
    "убей",
    "суицид",
    "детск порн",
    "порнография",
    "экстремизм",
    "насилие",
    "мошенничество",
    "обман банк",
    "кардинг",
]

_WORD_RE = re.compile(r"[^\w]+", re.UNICODE)


def normalize(text: str) -> str:
    """Приводит текст к нижнему регистру и заменяет разделители пробелами."""
    if not text:
        return ""
    return _WORD_RE.sub(" ", text.lower())


def check_prompt(prompt: str):
    """Проверяет промпт на запрещённые подстроки.

    Возвращает кортеж (is_ok: bool, matched: list[str]).
    Проверка идёт по нормализованной строке методом подстроки (includes).
    """
    norm = normalize(prompt or "")
    matched = [w for w in FORBIDDEN_WORDS if w in norm]
    return (len(matched) == 0, matched)
